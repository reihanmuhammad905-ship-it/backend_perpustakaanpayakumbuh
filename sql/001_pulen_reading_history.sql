-- Idempotent; dijalankan hanya pada database PULEN PostgreSQL 17 lokal.
-- Tidak menghapus pinjaman lama dan tidak mengubah autentikasi admin.
BEGIN;
ALTER TABLE public.loans
  ADD COLUMN IF NOT EXISTS tanggal_dikembalikan timestamp without time zone;

CREATE TABLE IF NOT EXISTS public.pulen_reading_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  book_id integer NOT NULL REFERENCES public.books(id) ON DELETE CASCADE,
  first_opened_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_opened_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  open_count integer NOT NULL DEFAULT 1 CHECK (open_count >= 1),
  CONSTRAINT pulen_reading_history_user_book_unique UNIQUE (user_id, book_id)
);
CREATE INDEX IF NOT EXISTS pulen_reading_history_last_opened_idx
  ON public.pulen_reading_history (user_id, last_opened_at DESC);
COMMIT;
